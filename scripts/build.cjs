const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n');
const images = Object.fromEntries([
    ['mention', 'mention-image.png', 'image/png'],
    ['copy', 'link-image.png', 'image/png'],
    ['loading', 'loading.gif', 'image/gif'],
].map(([name, file, mime]) => [name, `data:${mime};base64,${fs.readFileSync(path.join(root, file)).toString('base64')}`]));
const filename = 'cs-rin-ru-enhanced-mod.user.js';
const start = '// BEGIN BUNDLED ASSETS — generated by npm run build';
const end = '// END BUNDLED ASSETS';
let source = read(filename);
const blockStart = source.indexOf(start);
if (blockStart !== -1) {
    const blockEnd = source.indexOf(end, blockStart);
    if (blockEnd === -1) throw new Error('Unterminated bundled-assets block');
    source = source.slice(0, blockStart) + source.slice(blockEnd + end.length);
}
const assets = `${start}
// Edit config.html/config.css/config.js and src/*.js, then rebuild this block.
function getBundledImage(name) {
    return ${JSON.stringify(images)}[name];
}

function getBundledConfig() {
    return { html: ${JSON.stringify(read('config.html'))}, css: ${JSON.stringify(read('config.css'))} };
}

function initializeConfigUI() {
${read('config.js').split('\n').map(line => line ? '    ' + line : '').join('\n')}
}

${read('src/live-features.js')}
${read('src/quote-extras.js')}
${read('src/chat-runtime.js')}
${end}
`;
const built = source.trimEnd() + '\n\n' + assets;
if (process.argv.includes('--check')) {
    if (read(filename) !== built) {
        console.error('Bundled assets are stale. Run npm run build.');
        process.exitCode = 1;
    }
} else {
    fs.writeFileSync(path.join(root, filename), built, 'utf8');
    console.log('Bundled settings, styles and local features into the userscript.');
}
